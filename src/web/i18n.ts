export const translateError = (lang: Lang, message: string) => {
	if (lang !== 'ar') return message;
	if (ERRORS_AR[message]) return ERRORS_AR[message];
	const status = /^Something went wrong \((\d+)\)\.$/.exec(message);
	if (status) return `حدث خطأ (${status[1]}).`;
	if (/^Please choose a /.test(message)) return 'اختاري ملفاً من النوع المطلوب.';
	const ai = /^The AI had a problem \(([^)]*)\)\. Please try again\.$/.exec(message);
	if (ai) return `واجه الذكاء الاصطناعي مشكلة (${ai[1]}). حاولي مرة أخرى.`;
	return message;
};

export type I18n = {
	lang: Lang;
	t: (key: TKey, vars?: Record<string, string | number>) => string;
	tError: (message: string | null | undefined) => string;
};

export const makeI18n = (lang: Lang): I18n => ({
	lang,
	t: (key, vars) => translate(lang, key, vars),
	tError: (message) => (message ? translateError(lang, message) : ''),
});

export const I18nContext = createContext<I18n>(makeI18n('ar'));

export const useT = () => useContext(I18nContext);
